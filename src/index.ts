// ---- WWW ↔ non-WWW redirect (runs before everything else) ----
// Admin domain: always redirect www → non-www
// User domains: redirect based on site-level setting (www_preference: 'www' | 'non-www' | 'none')
app.use('*', async (c, next) => {
  const host = (c.req.header('host') || '').toLowerCase().replace(/:\d+$/, '');
  const adminDomain = (c.env.ADMIN_DOMAIN || '').toLowerCase().replace(/:\d+$/, '');
  const url = new URL(c.req.url);

  // --- Admin domain: force www → non-www ---
  if (adminDomain && host === `www.${adminDomain}`) {
    url.hostname = adminDomain;
    return c.redirect(url.toString(), 301);
  }

  // --- User domains: check www preference ---
  const isWww = host.startsWith('www.');
  const bareHost = isWww ? host.slice(4) : host;

  // Skip if host is admin domain (already handled) or workers.dev
  if (host === adminDomain || host.endsWith('.workers.dev')) {
    await next();
    return;
  }

  // Look up www_preference for this domain's site
  const domainToCheck = host; // check the actual host
  const siteDomain = await c.env.DB.prepare(
    'SELECT sd.site_id FROM site_domains sd WHERE sd.domain = ? OR sd.domain = ?'
  ).bind(bareHost, `www.${bareHost}`).first<{ site_id: number }>();

  if (siteDomain) {
    const pref = await c.env.DB.prepare(
      "SELECT value FROM settings WHERE site_id = ? AND key = 'www_preference'"
    ).bind(siteDomain.site_id).first<{ value: string }>();

    const wwwPref = pref?.value || 'none'; // default: no redirect

    if (wwwPref === 'non-www' && isWww) {
      // Redirect www → non-www
      url.hostname = bareHost;
      return c.redirect(url.toString(), 301);
    } else if (wwwPref === 'www' && !isWww) {
      // Redirect non-www → www
      url.hostname = `www.${host}`;
      return c.redirect(url.toString(), 301);
    }
  }

  await next();
});

