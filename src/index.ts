// Visitor gate exemptions. The gate (gate.js) only fronts PUBLIC customer-site
// traffic. Admin panel, API/webhooks, media and the management/admin domain must
// never be gated — otherwise desktop admins and server-to-server webhooks (which
// aren't mobile/Turkish) would be blocked. Proxied customer requests carry the
// real domain in `X-Site-Host`; a bare workers.dev/admin host with no such header
// is our own admin/debug surface, so it is exempt too.
function gateExempt(request: Request, env: Bindings): boolean {
  const url = new URL(request.url);
  const p = url.pathname;
  if (
    p === '/admin' || p.startsWith('/admin/') ||
    p === '/api' || p.startsWith('/api/') ||
    p.startsWith('/uploads/') ||
    p.startsWith('/git/')
  ) return true;

  const xsh = (request.headers.get('x-site-host') || '').trim().toLowerCase().replace(/:\d+$/, '');
  const wire = (request.headers.get('host') || '').toLowerCase().replace(/:\d+$/, '');
  const effective = xsh || wire;
  const admin = (env.ADMIN_DOMAIN || '').toLowerCase();
  if (admin && (effective === admin || effective === `www.${admin}`)) return true;
  // Bare workers.dev with no proxied customer domain = admin/debug access.
  if (!xsh && wire.endsWith('.workers.dev')) return true;
  return false;
}

// D1 aşırı-yük devre kesici. D1 boğulunca (queue dolu) render 500 verir; 500
// upstream cache'e alınamadığı için sel sürekli D1'e vurup çökük tutar. Devre
// kesici: D1 hatası görülünce kısa süre (cooldown) public HTML isteklerine D1'e
// DOKUNMADAN, upstream'in cache'leyebileceği kısa-TTL bir "yükleniyor" sayfası
// döneriz → sel micro-cache'te emilir → D1 kuyruğu boşalır → toparlar.
let d1CooldownUntil = 0;
function loadingResponse(): Response {
  const html = '<!doctype html><html lang="tr"><head><meta charset="utf-8">'
    + '<meta name="viewport" content="width=device-width,initial-scale=1">'
    + '<meta http-equiv="refresh" content="4"><meta name="robots" content="noindex">'
    + '<title>Lütfen bekleyin</title><style>body{font-family:system-ui,-apple-system,sans-serif;'
    + 'display:flex;align-items:center;justify-content:center;min-height:100vh;margin:0;background:#f8fafc;color:#475569}'
    + '.c{text-align:center;padding:24px}.s{width:34px;height:34px;border:3px solid #e2e8f0;border-top-color:#64748b;'
    + 'border-radius:50%;animation:sp 1s linear infinite;margin:0 auto 16px}@keyframes sp{to{transform:rotate(360deg)}}</style>'
    + '</head><body><div class="c"><div class="s"></div><p>Sayfa hazırlanıyor, lütfen birkaç saniye bekleyin…</p></div></body></html>';
  // 200 + kısa max-age: upstream micro-cache mutlaka cache'lesin (503'ü cache'lemeyebilir).
  return new Response(html, { status: 200, headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'public, max-age=3' } });
}

export default {
  // Reverse-proxy host override. An upstream proxy (e.g. our OpenResty edge)
  // can route a customer domain to this worker over its `*.workers.dev`
  // hostname while carrying the real domain in the `X-Site-Host` header. We
  // rewrite the request URL so canonical links, redirects and `c.req.url`
  // reflect the customer domain; `siteResolver` reads `X-Site-Host` directly
  // for site resolution. All fronted domains are ours, so no shared secret.
  fetch: async (request: Request, env: Bindings, ctx: ExecutionContext) => {
    // Sel kalkanı: `proxy.<ADMIN_DOMAIN>` fallback domenine X-Site-Host'SUZ gelen
    // istekler gerçek müşteri trafiği DEĞİL (o daima X-Site-Host taşır). Bot seli
    // bu bare domene vurup site çözemeden D1'i boğuyordu. D1'e dokunmadan ucuz,
    // önbelleklenebilir yanıt ver (ACME/.well-known hariç — SSL doğrulaması için).
    {
      const rawHost = (request.headers.get('host') || '').toLowerCase().replace(/:\d+$/, '');
      const fallback = `proxy.${(env.ADMIN_DOMAIN || 'fixyonet.com').toLowerCase()}`;
      if (rawHost === fallback && !request.headers.get('x-site-host')) {
        const p = new URL(request.url).pathname;
        if (!p.startsWith('/.well-known/')) {
          return new Response('OK', { status: 200, headers: { 'Content-Type': 'text/plain', 'Cache-Control': 'public, max-age=600' } });
        }
      }
    }

    // Visitor gate. Two levels of control:
    //  1) GATE_ENABLED === '1' — deployment master switch (only the gated
    //     worker sets it, so other deploy targets pay zero overhead).
    //  2) per-site `gate_enabled` setting — toggled from admin → Site Settings,
    //     so each customer site turns its own gate on/off. Default off.
    // Runs before the X-Site-Host rewrite; it only reads IP/country/UA/Accept
    // headers, which are host-independent.
    // reCAPTCHA doğrulama ucu — interstitial'ın otomatik POST'unu karşılar.
    // Gate'ten önce ele alınır (kendisi gate'e tabi değil). Token/skor geçerliyse
    // imzalı "insan" çerezi yazıp geldiği yola geri döner.
    if (env.GATE_ENABLED === '1' && env.RECAPTCHA_SECRET) {
      const tsUrl = new URL(request.url);
      if (tsUrl.pathname === '/__ts-verify' && request.method === 'POST') {
        const form = await request.formData();
        const token = String(form.get('g-recaptcha-response') || '');
        const rp = safePath(String(form.get('rp') || '/'));
        const vip = (request.headers.get('x-forwarded-for') || '').split(',')[0].trim()
          || request.headers.get('cf-connecting-ip') || undefined;
        const ok = await verifyRecaptcha(token, env.RECAPTCHA_SECRET, vip);
        if (ok) {
          return new Response(null, {
            status: 302,
            headers: { Location: rp, 'Set-Cookie': await makeHumanCookie(env.RECAPTCHA_SECRET), 'Cache-Control': 'no-store' },
          });
        }
        return new Response(
          '<!doctype html><meta charset="utf-8"><title>Doğrulama Başarısız</title><body style="font-family:sans-serif;text-align:center;padding:48px;color:#444"><div style="font-size:38px">&#9888;&#65039;</div><h2>Doğrulama Başarısız</h2><p style="color:#777">Bağlantınız doğrulanamadı. Lütfen tekrar deneyin.</p></body>',
          { status: 403, headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' } }
        );
      }
    }

    // Devre kesici: D1 cooldown'dayken public HTML isteğine D1'e vurmadan
    // cache'lenebilir "yükleniyor" sayfası dön (sel micro-cache'te emilsin).
    const wantsHtmlReq = (request.headers.get('Accept') || '').includes('text/html');
    // MAINTENANCE='1' → TÜM public (muaf olmayan) isteklere D1'e HİÇ dokunmadan
    // loading dön (botlar text/html göndermeyebilir; onları da yakala ki D1
    // sıfır sorguyla toparlasın). Cooldown ise devre kesicinin otomatik hâli.
    if (!gateExempt(request, env) && (env.MAINTENANCE === '1' || Date.now() < d1CooldownUntil)) {
      return loadingResponse();
    }

    let gatedNoStore = false;
    if (env.GATE_ENABLED === '1' && !gateExempt(request, env)) {
      const gateHost = (request.headers.get('x-site-host') || request.headers.get('host') || '')
        .trim().toLowerCase().replace(/:\d+$/, '');
      if (gateHost) {
       try {
        // Gate ayarlarını KV'de kısa süre cache'le — D1'i her istekte yorma
        // (aksi halde sel altında D1 boğulur ve tüm site 500 verir).
        let gsObj: Record<string, string> | null = null;
        const ck = `gatecfg:${gateHost}`;
        if (env.CACHE) {
          const cached = await env.CACHE.get(ck);
          if (cached) { try { gsObj = JSON.parse(cached); } catch { /* yok say */ } }
        }
        if (!gsObj) {
          const rows = await env.DB.prepare(
            "SELECT st.key, st.value FROM site_domains sd JOIN settings st ON st.site_id = sd.site_id AND st.key IN ('gate_enabled','gate_ignore_whitelist','gate_allow_mobile','gate_allow_desktop','gate_require_mobile','gate_require_turkish','gate_require_country','gate_require_no_proxy','gate_recaptcha','gate_block_title_tr','gate_block_text_tr','gate_block_title_en','gate_block_text_en') WHERE sd.domain = ?"
          ).bind(gateHost).all<{ key: string; value: string }>();
          gsObj = {};
          for (const r of (rows.results || [])) gsObj[r.key] = r.value;
          if (env.CACHE) ctx.waitUntil(env.CACHE.put(ck, JSON.stringify(gsObj), { expirationTtl: 30 }));
        }
        const gs = new Map(Object.entries(gsObj));
        if (gs.get('gate_enabled') === '1') {
          // Özel engelleme mesajı (admin) — TR başlığı doluysa nedeni belli
          // etmeden tüm engellerde bu gösterilir; boşsa varsayılan mesajlar.
          const btTr = (gs.get('gate_block_title_tr') || '').trim();
          const blockMessage = btTr
            ? {
                tr: [btTr, (gs.get('gate_block_text_tr') || '').trim()] as [string, string],
                en: [(gs.get('gate_block_title_en') || '').trim(), (gs.get('gate_block_text_en') || '').trim()] as [string, string],
              }
            : null;
          // Kurallar site bazlı; ayar yoksa varsayılan AÇIK ('0' ise kapalı).
          // Cihaz izinleri ayrı: mobil varsayılan AÇIK, masaüstü varsayılan KAPALI.
          const blocked = await runGate(request, env, {
            ignoreWhitelist: gs.get('gate_ignore_whitelist') === '1',
            allowMobile: gs.get('gate_allow_mobile') !== '0',
            allowDesktop: gs.get('gate_allow_desktop') === '1',
            requireTurkish: gs.get('gate_require_turkish') !== '0',
            requireCountry: gs.get('gate_require_country') !== '0',
            requireNoProxy: gs.get('gate_require_no_proxy') !== '0',
            blockMessage,
          });
          if (blocked) return blocked;
          // Kurallar geçti. reCAPTCHA açıksa ve geçerli "insan" çerezi yoksa,
          // içerik yerine görünmez doğrulama sayfasını sun (token alan girer).
          if (
            gs.get('gate_recaptcha') === '1' &&
            env.RECAPTCHA_SITE_KEY && env.RECAPTCHA_SECRET &&
            !(await hasValidHumanCookie(request, env.RECAPTCHA_SECRET))
          ) {
            return interstitialHtml(env.RECAPTCHA_SITE_KEY, new URL(request.url).pathname + new URL(request.url).search);
          }
          // Ziyaretçi geçti AMA sayfa gate'e tabi: upstream proxy/CDN bu sayfayı
          // önbelleğe alıp ENGELLENMESİ gereken başka bir ziyaretçiye sunmasın
          // diye yanıtı önbelleklenemez işaretle (proxy her istekte gate'e uğrar).
          gatedNoStore = true;
        }
       } catch (e) {
        // D1/KV hatası (ör. D1 aşırı yük) → kapıyı atla, site ayakta kalsın.
        console.error('[gate] skipped:', (e as Error)?.message);
       }
      }
    }

    const proxied = request.headers.get('x-site-host');
    if (proxied) {
      const clean = proxied.trim().toLowerCase().replace(/:\d+$/, '');
      if (/^[a-z0-9.-]+$/.test(clean)) {
        const url = new URL(request.url);
        url.hostname = clean;
        url.port = '';
        // Rewrite both the URL and the `Host` header so every host-reader in
        // the app (landing/admin routing, www redirects, canonical links)
        // sees the customer domain uniformly, not the workers.dev name.
        const headers = new Headers(request.headers);
        headers.set('host', clean);
        const init: RequestInit = { method: request.method, headers };
        if (request.method !== 'GET' && request.method !== 'HEAD') {
          init.body = request.body;
          (init as { duplex?: 'half' }).duplex = 'half';
        }
        request = new Request(url.toString(), init);
      }
    }
    let response: Response;
    try {
      response = await app.fetch(request, env, ctx);
    } catch (e) {
      // Worker seviyesinde yakalanmamış hata (ör. D1 throw) → devre kesiciyi tetikle.
      d1CooldownUntil = Date.now() + 12000;
      console.error('[fetch] threw, cooldown 12s:', (e as Error)?.message);
      if (wantsHtmlReq) return loadingResponse();
      throw e;
    }
    // CMS 5xx döndüyse (D1 aşırı yük vb.) → devre kesiciyi tetikle, sayfayı emilebilir yap.
    if (response.status >= 500 && !gateExempt(request, env)) {
      d1CooldownUntil = Date.now() + 12000;
      return loadingResponse();
    }
    if (gatedNoStore) {
      const r = new Response(response.body, response);
      r.headers.set('Cache-Control', 'no-store, no-cache, must-revalidate, max-age=0');
      r.headers.delete('ETag');
      r.headers.delete('Last-Modified');
      return r;
    }
    return response;
  },
  async scheduled(event: ScheduledEvent, env: Bindings, ctx: ExecutionContext) {
    const now = new Date().toISOString();
    // Publish scheduled posts
    ctx.waitUntil(
      env.DB.prepare(
        `UPDATE posts SET status = 'publish', updated_at = datetime('now') WHERE status = 'scheduled' AND published_at <= ?`
      ).bind(now).run()
    );
    // Poll processing Contety contents
    ctx.waitUntil(processContetyPolling(env));
    // Check pending domain NS propagation
    ctx.waitUntil(checkPendingDomains(env));
    // Expire ended subscriptions
    ctx.waitUntil(expireSubscriptions(env.DB));
    // Cleanup old plugin execution logs (30 days retention)
    ctx.waitUntil(
      env.DB.prepare("DELETE FROM plugin_execution_logs WHERE created_at < datetime('now', '-30 days')").run()
    );
    // Refresh the system-status snapshot when it is older than its TTL
    // (cron fires every minute; the snapshot only re-fetches every ~5 min).
    ctx.waitUntil(
      getStatusSnapshot(env).then((snap) =>
        isStale(snap) ? refreshStatusSnapshot(env) : null
      )
    );
  },
};
