// Helper: check if host is an admin domain (primary or workers.dev fallback)
function isAdminHost(host: string, env: Bindings): boolean {
  const adminDomain = (env.ADMIN_DOMAIN || '').toLowerCase().replace(/:\d+$/, '');
  if (adminDomain && (host === adminDomain || host === `www.${adminDomain}`)) return true;
  // Also allow workers.dev subdomain as admin
  if (host.endsWith('.workers.dev')) return true;
  return false;
}

