// Contety callback (public endpoint — Contety sends POST when async content is ready)
//
// If `global_settings.contety_callback_secret` is configured we require
// callers to present it via `X-Contety-Secret`. The secret is optional for
// backwards compatibility but should be set in production to keep
// strangers from probing tracking record state by guessing content_ids.
app.post('/api/contety/callback', async (c) => {
  try {
    const secretRow = await c.env.DB.prepare(
      "SELECT value FROM global_settings WHERE key = 'contety_callback_secret'"
    ).first<{ value: string }>();
    if (secretRow?.value) {
      const provided = c.req.header('x-contety-secret') || '';
      if (provided !== secretRow.value) {
        return c.json({ error: 'Unauthorized' }, 401);
      }
    }

    const body = await c.req.json<{ process_type?: string; content_id?: number; status?: string }>();
    if (!body.content_id || !body.status) {
      return c.json({ error: 'Missing content_id or status' }, 400);
    }

    // Find the tracking record
    const record = await c.env.DB.prepare(
      'SELECT cc.*, cfg.auto_import, cfg.default_status, cfg.default_category_id, cfg.default_author_id, cfg.api_key as site_api_key FROM contety_contents cc LEFT JOIN contety_configs cfg ON cfg.site_id = cc.site_id WHERE cc.contety_content_id = ? AND cc.status = ?'
    ).bind(body.content_id, 'processing').first<any>();

    if (!record) {
      return c.json({ success: true, message: 'No matching record' });
    }

    if (body.status === 'completed') {
      // Get API key for fetching content detail
      const apiKey = record.site_api_key || await c.env.DB.prepare(
        'SELECT api_key FROM global_contety_config WHERE is_enabled = 1 LIMIT 1'
      ).bind().first<any>().then((r: any) => r?.api_key);

      if (apiKey && record.auto_import === 1) {
        const { getContentDetail, importContentAsPost } = await import('./lib/contety');
        const detail = await getContentDetail(apiKey, body.content_id);

        if (detail.status === 'completed') {
          const postId = await importContentAsPost(c.env.DB, c.env.R2, record.site_id, detail, {
            default_status: record.default_status || 'draft',
            default_category_id: record.default_category_id,
            default_author_id: record.default_author_id,
          });

          await c.env.DB.prepare(
            'UPDATE contety_contents SET status = ?, post_id = ?, title = ?, updated_at = datetime(?) WHERE id = ?'
          ).bind('completed', postId, detail.title, new Date().toISOString(), record.id).run();

          await c.env.DB.prepare(
            'INSERT INTO contety_logs (site_id, action, contety_content_id, post_id, credits_used, status) VALUES (?, ?, ?, ?, ?, ?)'
          ).bind(record.site_id, 'callback_import', body.content_id, postId, detail.credits || 0, 'success').run();
        }
      } else {
        // Just mark as completed, user will manually import
        await c.env.DB.prepare(
          'UPDATE contety_contents SET status = ?, updated_at = datetime(?) WHERE id = ?'
        ).bind('completed', new Date().toISOString(), record.id).run();
      }
    } else if (body.status === 'failed') {
      await c.env.DB.prepare(
        'UPDATE contety_contents SET status = ?, error_message = ?, updated_at = datetime(?) WHERE id = ?'
      ).bind('failed', 'Content generation failed on Contety', new Date().toISOString(), record.id).run();

      await c.env.DB.prepare(
        'INSERT INTO contety_logs (site_id, action, contety_content_id, status, error_message) VALUES (?, ?, ?, ?, ?)'
      ).bind(record.site_id, 'callback_failed', body.content_id, 'failed', 'Content generation failed').run();
    }

    return c.json({ success: true });
  } catch (err: any) {
    console.error('Contety callback error:', err.message);
    return c.json({ error: 'Internal error' }, 500);
  }
});

