// ---- Media serving (R2) ----
// Supports both:
//   /uploads/{path}           → siteId from domain resolution (public sites)
//   /uploads/s/{siteId}/{path} → explicit siteId in URL (admin panel)
app.get('/uploads/*', async (c) => {
  let siteId = c.get('siteId');
  let path = new URL(c.req.url).pathname.replace('/uploads/', '');

  // Support explicit site prefix: /uploads/s/{siteId}/...
  const siteMatch = path.match(/^s\/(\d+)\/(.*)/);
  if (siteMatch) {
    siteId = parseInt(siteMatch[1]);
    path = siteMatch[2];
  }

  if (!siteId) return c.notFound();

  const key = `sites/${siteId}/uploads/${path}`;

  const object = await c.env.R2.get(key);
  if (!object) return c.notFound();

  const contentType = object.httpMetadata?.contentType || 'application/octet-stream';

  const headers = new Headers();
  headers.set('Content-Type', contentType);
  headers.set('Cache-Control', 'public, max-age=31536000, immutable');
  headers.set('ETag', object.etag);
  headers.set('X-Content-Type-Options', 'nosniff');

  // SVG/HTML/XML can carry executable script. They still render fine from
  // <img> tags, but when opened directly this CSP keeps any embedded script
  // from running in the site's origin (stored-XSS via upload).
  if (/svg|html|xml/i.test(contentType)) {
    headers.set('Content-Security-Policy', "default-src 'none'; style-src 'unsafe-inline'; sandbox");
  }

  return new Response(object.body, { headers });
});

