export default {
  fetch: app.fetch,
  async scheduled(event: ScheduledEvent, env: Bindings, ctx: ExecutionContext) {
    const now = new Date().toISOString();
    // Publish scheduled posts
    ctx.waitUntil(
      env.DB.prepare(
        `UPDATE posts SET status = 'publish', updated_at = datetime('now') WHERE status = 'scheduled' AND published_at <= ?`
      ).bind(now).run()
    );
    // Poll processing Contety contents
    ctx.waitUntil(processContetyPolling(env));
    // Check pending domain NS propagation
    ctx.waitUntil(checkPendingDomains(env));
    // Expire ended subscriptions
    ctx.waitUntil(expireSubscriptions(env.DB));
    // Cleanup old plugin execution logs (30 days retention)
    ctx.waitUntil(
      env.DB.prepare("DELETE FROM plugin_execution_logs WHERE created_at < datetime('now', '-30 days')").run()
    );
  },
};
