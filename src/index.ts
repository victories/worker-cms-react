// AMP custom domain middleware — if the request's domain is set as a site's amp_custom_domain,
// serve all /:slug paths as AMP content
app.use('*', async (c, next) => {
  const siteId = c.get('siteId');
  if (!siteId) { await next(); return; }

  const path = new URL(c.req.url).pathname;
  // Only intercept simple slug paths, not /api, /admin, /uploads, /amp, /feed, /sitemap etc.
  if (path.startsWith('/api/') || path.startsWith('/admin') || path.startsWith('/uploads/') ||
      path.startsWith('/amp') || path.startsWith('/feed') || path.startsWith('/sitemap')) {
    await next();
    return;
  }

  // Check if this domain is an AMP custom domain
  const host = (c.req.header('host') || '').toLowerCase().replace(/:\d+$/, '');
  const ampDomainSetting = await c.env.DB.prepare(
    "SELECT value FROM settings WHERE site_id = ? AND key = 'amp_custom_domain'"
  ).bind(siteId).first<{ value: string }>();

  if (!ampDomainSetting || !ampDomainSetting.value || ampDomainSetting.value.toLowerCase() !== host) {
    await next();
    return;
  }

  // This IS the AMP custom domain — import and call the dynamic AMP renderer
  const { renderAmpForPost } = await import('./routes/public/amp/dynamic');
  const site = c.get('site') as any;
  const defaultLang = site?.default_language || 'tr';

  // Parse slug from path: /:slug or /:lang/:slug
  const parts = path.split('/').filter(Boolean);
  if (parts.length === 1) {
    return renderAmpForPost(c, defaultLang, parts[0]);
  } else if (parts.length === 2 && /^[a-z]{2}$/.test(parts[0])) {
    return renderAmpForPost(c, parts[0], parts[1]);
  }

  await next();
});

