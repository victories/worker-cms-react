#!/usr/bin/env node
/**
 * Build public-side Tailwind CSS and embed it as a TypeScript module.
 *
 * Why the TS wrapper? Cloudflare Workers don't have filesystem access, so
 * we can't read a .css file at runtime. Three common options:
 *
 *   1. Serve the CSS as a static asset via Worker Assets / [site] bucket.
 *   2. Inline the CSS into the HTML <style> block at render time.
 *   3. Import the CSS as a string constant bundled into the worker code.
 *
 * We use option 3 for Faz 0 because it's the simplest — no extra
 * wrangler config, works in dev and production the same way, and the
 * whole compiled bundle is small (< 60KB gzipped for shadcn + utilities).
 *
 * The generated file is written to src/ssr/__generated__/tailwind.ts and
 * should be gitignored. scripts/build-public-css.mjs runs before every
 * `wrangler dev` and `wrangler deploy` via npm scripts.
 */

import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

const INPUT = resolve(ROOT, 'public-styles/input.css');
const CONFIG = resolve(ROOT, 'public-styles/tailwind.config.ts');
const TMP_OUT = resolve(ROOT, 'public-styles/.tmp.output.css');
const GENERATED = resolve(ROOT, 'src/ssr/__generated__/tailwind.ts');

// 1. Run Tailwind CLI from within public-styles/ so relative content globs
//    in tailwind.config.ts (../src, ../packages) resolve correctly.
console.log('[build-public-css] compiling Tailwind…');
const start = Date.now();
try {
  execSync(
    `npx tailwindcss -c "${CONFIG}" -i "${INPUT}" -o "${TMP_OUT}" --minify`,
    { stdio: 'inherit', cwd: ROOT }
  );
} catch (err) {
  console.error('[build-public-css] Tailwind CLI failed');
  process.exit(1);
}

// 2. Read the compiled CSS and wrap it in a TypeScript module so the
//    worker can import it as a regular string constant.
const css = readFileSync(TMP_OUT, 'utf8');
const sizeKb = (Buffer.byteLength(css, 'utf8') / 1024).toFixed(1);

mkdirSync(dirname(GENERATED), { recursive: true });
const banner =
  '// AUTO-GENERATED by scripts/build-public-css.mjs — do not edit.\n' +
  '// Source: public-styles/input.css + tailwind.config.ts\n';

writeFileSync(
  GENERATED,
  banner +
    'export const TAILWIND_CSS = ' +
    JSON.stringify(css) +
    ';\n',
  'utf8'
);

// 3. Clean up the intermediate file.
try {
  execSync(process.platform === 'win32' ? `del "${TMP_OUT}"` : `rm "${TMP_OUT}"`,
    { stdio: 'ignore', shell: true });
} catch {
  // best effort
}

const elapsed = Date.now() - start;
console.log(`[build-public-css] done (${sizeKb} KB, ${elapsed} ms) → ${GENERATED}`);
