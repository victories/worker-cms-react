#!/usr/bin/env node
/**
 * Build public-side Tailwind CSS and embed it as a TypeScript module.
 *
 * Why the TS wrapper? Cloudflare Workers don't have filesystem access, so
 * we can't read a .css file at runtime. Three common options:
 *
 *   1. Serve the CSS as a static asset via Worker Assets / [site] bucket.
 *   2. Inline the CSS into the HTML <style> block at render time.
 *   3. Import the CSS as a string constant bundled into the worker code.
 *
 * We use option 3 for Faz 0 because it's the simplest — no extra
 * wrangler config, works in dev and production the same way, and the
 * whole compiled bundle is small (< 60KB gzipped for shadcn + utilities).
 *
 * The generated file is written to src/ssr/__generated__/tailwind.ts and
 * should be gitignored. scripts/build-public-css.mjs runs before every
 * `wrangler dev` and `wrangler deploy` via npm scripts.
 */

import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

const INPUT = resolve(ROOT, 'public-styles/input.css');

// Each entry produces one bundle. The default `publisher` bundle scans
// the whole SSR + UI tree (with @tailwindcss/typography). The
// `landing` bundle uses a narrower scan that skips <Prose> so the
// .prose rules — ~34 KB — don't get inlined into landing pages.
const BUNDLES = [
  {
    name: 'publisher',
    config: 'public-styles/tailwind.config.ts',
    out: 'src/ssr/__generated__/tailwind.ts',
    constName: 'TAILWIND_CSS',
  },
  {
    name: 'landing',
    config: 'public-styles/tailwind.landing.config.ts',
    out: 'src/ssr/__generated__/tailwind-landing.ts',
    constName: 'TAILWIND_LANDING_CSS',
  },
];

for (const b of BUNDLES) {
  const config = resolve(ROOT, b.config);
  const tmp = resolve(ROOT, `public-styles/.tmp.${b.name}.css`);
  const generated = resolve(ROOT, b.out);

  console.log(`[build-public-css] compiling Tailwind (${b.name})…`);
  const start = Date.now();
  try {
    execSync(
      `npx tailwindcss -c "${config}" -i "${INPUT}" -o "${tmp}" --minify`,
      { stdio: 'inherit', cwd: ROOT }
    );
  } catch (err) {
    console.error(`[build-public-css] Tailwind CLI failed for ${b.name}`);
    process.exit(1);
  }

  const css = readFileSync(tmp, 'utf8');
  const sizeKb = (Buffer.byteLength(css, 'utf8') / 1024).toFixed(1);

  mkdirSync(dirname(generated), { recursive: true });
  const banner =
    '// AUTO-GENERATED by scripts/build-public-css.mjs — do not edit.\n' +
    `// Source: public-styles/input.css + ${b.config}\n`;

  writeFileSync(
    generated,
    banner + `export const ${b.constName} = ` + JSON.stringify(css) + ';\n',
    'utf8'
  );

  try {
    execSync(
      process.platform === 'win32' ? `del "${tmp}"` : `rm "${tmp}"`,
      { stdio: 'ignore', shell: true }
    );
  } catch {
    // best effort
  }

  const elapsed = Date.now() - start;
  console.log(
    `[build-public-css] ${b.name} done (${sizeKb} KB, ${elapsed} ms) → ${generated}`
  );
}
